// Bundles mirror-viewer/viewer.ts (three.js) into one HTML string the app
// loads into a WebView (native) or an iframe (web). Run: npm run build:mirror-viewer
const { buildSync } = require('esbuild');
const fs = require('fs');
const path = require('path');

const out = buildSync({
  entryPoints: [path.join(__dirname, 'viewer.ts')],
  bundle: true,
  minify: true,
  format: 'iife',
  target: ['safari15'],
  write: false,
  legalComments: 'none',
});
const js = out.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const html =
  '<!doctype html><html><head><meta charset="utf-8">' +
  '<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no">' +
  '<style>html,body{margin:0;height:100%;overflow:hidden;background:transparent;touch-action:none;-webkit-user-select:none;user-select:none}' +
  'canvas{display:block;width:100%;height:100%;touch-action:none}</style></head>' +
  '<body><canvas id="c"></canvas><script>' + js + '</script></body></html>';
const target = path.join(__dirname, '..', 'src', 'mirror', 'viewerHtml.generated.ts');
fs.writeFileSync(
  target,
  '// Generated by mirror-viewer/build.js from mirror-viewer/viewer.ts. Do not edit.\n' +
    '// three.js r' + JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'node_modules', 'three', 'package.json'), 'utf8')).version + ' (MIT) is bundled inline.\n' +
    'export const VIEWER_HTML = ' + JSON.stringify(html) + ';\n',
);
console.log('wrote', path.relative(process.cwd(), target), (html.length / 1024).toFixed(0) + ' KB');
